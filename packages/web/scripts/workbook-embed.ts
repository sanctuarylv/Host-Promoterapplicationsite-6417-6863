/**
 * Regenerates src/api/ops/staffing/canonical-source.ts from the reviewed
 * canonical workbook export so the server-side preview (/staff/taxonomy and the
 * readiness row) reads exactly the bytes that were reviewed.
 *
 *   bun scripts/workbook-embed.ts data/staffing/sanctuary_lv_group_36_role_canonical_v1.csv
 *
 * Opens no database. Lines are stored as JSON strings and re-joined with the
 * file's own line ending so the sha256 is byte-identical (template literals
 * would normalise CRLF to LF and change the hash). tests/staffing-taxonomy.test.ts
 * fails if the embedded copy and the data file ever drift apart.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { basename, join } from "node:path";

const file = process.argv[2];
if (!file) {
  console.error("usage: bun scripts/workbook-embed.ts <canonical.csv>");
  process.exit(2);
}
const bytes = readFileSync(file);
const text = bytes.toString("utf8");
const eol = text.includes("\r\n") ? "\r\n" : "\n";
const trailing = text.endsWith(eol);
const lines = (trailing ? text.slice(0, -eol.length) : text).split(eol);
if (lines.some((l) => l.includes("\r") || l.includes("\n"))) throw new Error("mixed line endings — refusing to embed");
const sha = createHash("sha256").update(bytes).digest("hex");

const out = `/**
 * GENERATED by scripts/workbook-embed.ts — do not edit by hand.
 * Verbatim copy of data/staffing/${basename(file)} (sha256 ${sha}).
 * Embedded so the staff preview reads the reviewed bytes without filesystem access.
 */
export const CANONICAL_V1_FILE = ${JSON.stringify(`data/staffing/${basename(file)}`)};
export const CANONICAL_V1_SHA256 = ${JSON.stringify(sha)};
const LINES: string[] = [
${lines.map((l) => `  ${JSON.stringify(l)},`).join("\n")}
];
export const CANONICAL_V1_CSV = LINES.join(${JSON.stringify(eol)})${trailing ? ` + ${JSON.stringify(eol)}` : ""};
`;
const target = join(import.meta.dir, "../src/api/ops/staffing/canonical-source.ts");
writeFileSync(target, out);
console.log(`[workbook-embed] wrote ${target} (${lines.length} lines, sha256 ${sha})`);
